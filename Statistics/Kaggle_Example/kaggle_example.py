def cramers_v(x,y):
  tablo =pd.crosstab(x,y)
  chi2 = stats.chi2_contingency(tablo)[0]
  n =tablo.sum().sum()
  k= min(tablo.shape)-1
  return np.sqrt(chi2/(n*k))

