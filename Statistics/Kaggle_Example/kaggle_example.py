def ortalama_guven_aralığı(seri,guven=0.95):
  veri = seri.dropna()
  n = len(veri)
  ortalama = veri.mean()
  sem = stats.sem(veri) # standart error of the mean
  t_kritik = stats.t.ppf((1+guven)/2 ,df =n-1)
  hata_payi = t_kritik*sem
  return ortalama,ortalama-hata_payi,ortalama+hata_payi

